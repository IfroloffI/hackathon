def typo(word: str, rng: random.Random) -> str:
    letters = [i for i, ch in enumerate(word) if ch.isalpha()]
    if len(letters) < 5:
        return word
    i = rng.choice(letters[1:-1])
    if rng.random() < 0.5:
        return word[:i] + word[i + 1:]  # пропуск буквы
    return word[:i] + word[i + 1] + word[i] + word[i + 2:]  # перестановка соседних


def render(entity: str, rng: random.Random) -> str:
    x = typo(entity, rng) if rng.random() < TYPO_P else entity
    text = rng.choice(TEMPLATES).format(x=x)
    if rng.random() < LOWER_P:
        text = text.lower()
    if rng.random() < 0.3:
        text = text.replace("ё", "е").replace("Ё", "Е")
    return text


def build(npc: str, spec: dict[str, list[str]], rng: random.Random) -> list[tuple[str, int, str]]:
    n_pos = round(ROWS * POS_SHARE)
    n_neg = ROWS - n_pos
    n_junk = round(n_neg * JUNK_SHARE)
    rows: dict[str, tuple[int, str]] = {}

    def add(target: int, label: int, pool: list[str], free: list[str]) -> None:
        start = sum(1 for v in rows.values() if v[0] == label)
        # Свободные ответы — как есть (без шаблона).
        for t in free:
            rows.setdefault(t, (label, t))
        # Каждая сущность — хотя бы раз: иначе её слова модели незнакомы, и решает соседнее
        # слово («Юрий Долгорукий» прошёл бы как «Юрий» Гагарин).
        for e in rng.sample(pool, len(pool)):
            if sum(1 for v in rows.values() if v[0] == label) >= start + target:
                break
            for _ in range(20):
                if rows.setdefault(render(e, rng), (label, e)) == (label, e):
                    break
        tries = 0
        while sum(1 for v in rows.values() if v[0] == label) < start + target and tries < 50_000:
            tries += 1
            e = rng.choice(pool)
            rows.setdefault(render(e, rng), (label, e))

    add(n_pos, 1, spec["pos"], spec["pos_free"])
    add(n_neg - n_junk, 0, spec["neg"], spec["neg_free"])
    junk_before = sum(1 for v in rows.values() if v[0] == 0)
    while sum(1 for v in rows.values() if v[0] == 0) < junk_before + n_junk:
        t = rng.choice(JUNK)
        t = t if rng.random() < 0.6 else rng.choice([t.capitalize(), t + "!", t + "?", t + "..."])
        rows.setdefault(t, (0, "junk"))

    pos = [(t, l, e) for t, (l, e) in rows.items() if l == 1][:n_pos]
    neg = [(t, l, e) for t, (l, e) in rows.items() if l == 0][:n_neg]
    out = pos + neg
    rng.shuffle(out)
    return out


def main() -> None:
    out_dir = Path(__file__).parent / "data"
    out_dir.mkdir(exist_ok=True)
    for npc, spec in NPCS.items():
        rng = random.Random(f"{SEED}-{npc}")
        rows = build(npc, spec, rng)
        with open(out_dir / f"{npc}.csv", "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(["text", "label", "entity"])
            w.writerows(rows)
        pos = sum(r[1] for r in rows)
        print(f"{npc}: {len(rows)} строк, верных {pos} ({pos / len(rows):.0%})")


if __name__ == "__main__":
    main()
